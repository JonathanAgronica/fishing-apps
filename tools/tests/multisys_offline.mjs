import puppeteer from 'puppeteer-core';import {execSync} from 'child_process';
const BASE='http://localhost:18080/fishing-apps/';
const srvOff=()=>{try{execSync("pkill -f 'http.server 18080'");}catch(e){}execSync('sleep 0.5');};
const srvOn=()=>{execSync("cd /tmp/srv && (nohup python3 -m http.server 18080 >/tmp/srv.log 2>&1 &) ; sleep 1");};
const b=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox']});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const ctx=await b.createBrowserContext();const p=await ctx.newPage();const errs=[];
p.on('pageerror',e=>errs.push('pageerror: '+e.message));
await p.setViewport({width:400,height:850,deviceScaleFactor:2,isMobile:true,hasTouch:true});
const ready=async id=>{await p.waitForSelector('body[data-sys-ready="'+id+'"]',{timeout:60000});await p.waitForSelector('body[data-bt-ready="1"]',{timeout:60000});};
srvOn();
await p.goto(BASE+'#baffle',{waitUntil:'networkidle0'});await ready('baffle');await p.evaluate(()=>navigator.serviceWorker.ready);await sleep(1500);
await p.goto(BASE+'?sys=burnett-river#baffle',{waitUntil:'networkidle0'});await ready('burnett-river');await sleep(1000);
srvOff();
await p.goto(BASE+'?sys=burnett-river#baffle',{waitUntil:'domcontentloaded'});await ready('burnett-river');
console.log('server down, burnett (opened before):',await p.$eval('#bt-stats',e=>e.innerText.slice(0,60).replace(/\n/g,' | ')));
await p.goto(BASE+'?sys=kolan-river#baffle',{waitUntil:'domcontentloaded'});await sleep(3000);
console.log('server down, kolan (never opened):',await p.evaluate(()=>{const e=document.getElementById('sysLoading');return e?e.innerText:'(no banner) sysReady='+document.body.dataset.sysReady;}));
await p.screenshot({path:'/workspace/multisys/shots/offline-unsaved.png'});
srvOn();
await p.goto(BASE+'?sys=burnett-river#baffle',{waitUntil:'networkidle0'});await ready('burnett-river');
await p.evaluate(()=>{window.confirm=()=>true;});await p.click('#sysOff');
await p.waitForFunction(()=>/saved|failed/.test(document.getElementById('sysMsg').innerText),{timeout:120000});console.log('download:',await p.$eval('#sysMsg',e=>e.innerText));
srvOff();
await p.goto(BASE+'?sys=kolan-river#map',{waitUntil:'domcontentloaded'});await ready('kolan-river');console.log('server down, kolan after download:',await p.$eval('#bt-locInfo',e=>e.innerText.slice(0,90)));
await sleep(3000);await p.screenshot({path:'/workspace/multisys/shots/offline-kolan-map.png'});
await p.goto(BASE+'?sys=baffle#baffle',{waitUntil:'domcontentloaded'});await ready('baffle');console.log('server down, baffle:',await p.$eval('#bt-locInfo',e=>e.innerText.slice(0,60)));
srvOn();
console.log('pageerrors',errs);await b.close();
